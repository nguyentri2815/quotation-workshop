import { test, expect } from '@playwright/test'
const url = '/#journey=2&step=3&sub=3&tab=build&buildView=dependencies&dependencyNode=props'

test('3.4: cây thật, đích props/type/call, chọn vị trí nguồn, quay lại và URL', async ({ page }) => {
  await page.goto(url)
  const dependency = page.getByTestId('step-dependencies')
  const tree = page.getByLabel('Cây phụ thuộc checkpoint 03-summary', { exact: true })
  await expect(dependency.locator('.react-flow')).toHaveCount(0)
  const props = tree.locator('[data-dependency-node="props"]')
  await expect(props.locator('[data-relation-to="summary"]')).toBeVisible()
  const summary = tree.locator('[data-dependency-node="summary"]')
  await expect(summary.locator('[data-relation-to="premium-type"]')).toBeVisible()
  await expect(summary.locator('[data-relation-to="format"]')).toBeVisible()
  await page.screenshot({ path: '.verification/dependency-tree-resume-20261030/step-3-4.png', fullPage: true })
  await tree.getByRole('button', { name: 'quotation', exact: true }).click()
  await expect(tree.getByRole('button', { name: 'quotation', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await props.locator('[data-relation-to="summary"]').click()
  await expect(summary.locator('[data-dependency-selected="true"]')).toBeVisible()
  await expect(page.getByLabel('Chi tiết dependency')).toContainText('Truyền dữ liệu premium và stale; không truyền callback')
  await summary.locator('[data-relation-to="format"]').click()
  const format = tree.locator('[data-dependency-node="format"]')
  await expect(format.locator('[data-dependency-selected="true"]')).toBeVisible()
  await expect(tree.getByRole('button', { name: 'quotation', exact: true })).toHaveAttribute('aria-expanded', 'true')
  const revealed = await format.locator('[data-dependency-selected="true"]').boundingBox()
  const treeBounds = await tree.getByTestId('tree-scroll').boundingBox()
  expect(revealed!.y).toBeGreaterThanOrEqual(treeBounds!.y)
  expect(revealed!.y + revealed!.height).toBeLessThanOrEqual(treeBounds!.y + treeBounds!.height)
  await expect(page.getByLabel('Vị trí code nguồn')).toHaveValue('0')
  await expect(page.getByLabel('Vị trí code nguồn').locator('option')).toHaveCount(4)
  await page.getByLabel('Vị trí code nguồn').selectOption('2')
  await expect(page.getByLabel('Quan hệ đang chọn')).toContainText('formatMoney(premium.total)')
  await page.getByRole('button', { name: 'Xem code nguồn', exact: true }).click()
  const code = page.getByLabel('Source mẫu', { exact: true })
  await expect(code).toHaveAttribute('data-file', 'components/PremiumSummary.tsx')
  await expect(code.locator('[data-explained="true"]')).toHaveCount(1)
  await expect(code.locator('[data-explained="true"]')).toContainText('formatMoney(premium.total)')
  const before = new URLSearchParams(new URL(page.url()).hash.slice(1))
  await page.getByRole('tab', { name: 'Phụ thuộc của bước', exact: true }).click()
  const after = new URLSearchParams(new URL(page.url()).hash.slice(1))
  expect(after.get('file')).toBe(before.get('file')); expect(after.get('symbol')).toBe(before.get('symbol'))
  await page.getByRole('button', { name: 'Quay lại lựa chọn trước', exact: true }).click()
  await expect(summary.locator('[data-dependency-selected="true"]')).toBeVisible()
  await page.goBack()
  await expect(page.getByLabel('Quan hệ đang chọn')).toContainText('formatMoney')
  await page.goForward()
  await expect(summary.locator('[data-dependency-selected="true"]')).toBeVisible()
  await page.reload()
  await expect(tree.locator('[data-dependency-node="summary"] [data-dependency-selected="true"]')).toBeVisible()
  await expect(page.getByLabel('Checkpoint mẫu', { exact: true })).toHaveValue('03-summary')
  await page.screenshot({ path: '.verification/dependency-tree-20261030/chain.png', fullPage: true })
})

test('chọn file giữ file, không tự đổi symbol; quan hệ tương lai không tự chuyển mốc', async ({ page }) => {
  await page.goto(url)
  const tree = page.getByLabel('Cây phụ thuộc checkpoint 03-summary', { exact: true })
  await tree.locator('[data-tree-file="pages/QuotationDetail.tsx"] [data-file="pages/QuotationDetail.tsx"]').click()
  await expect(page.getByLabel('Chi tiết dependency')).toContainText('Đang chọn file tại mốc 03-summary')
  await expect(tree.locator('[data-dependency-selected="true"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Xem source file', exact: true }).click()
  await expect(page.getByLabel('Source mẫu', { exact: true })).toHaveAttribute('data-file', 'pages/QuotationDetail.tsx')
  await page.getByRole('tab', { name: 'Phụ thuộc của bước', exact: true }).click()
  await expect(page.getByLabel('Chi tiết dependency')).toContainText('Đang chọn file tại mốc 03-summary')
  await page.getByLabel('Phạm vi dependency').selectOption('step')
  await page.getByLabel('Xem phần chưa hình thành', { exact: true }).check()
  await page.getByLabel('Chọn dependency', { exact: true }).selectOption('calculate')
  const calculate = tree.locator('[data-dependency-node="calculate"]')
  const futureEdge = calculate.locator('[data-relation="calculate~Gọi~price"]')
  await expect(futureEdge).toContainText('Chưa hình thành · từ mốc 05')
  await futureEdge.locator('[data-relation-to="price"]').click()
  await expect(page.getByLabel('Quan hệ đang chọn')).toContainText('Quan hệ chưa hình thành tại 03-summary')
  await expect(page.getByLabel('Checkpoint mẫu', { exact: true })).toHaveValue('03-summary')
  await page.getByLabel('Quan hệ đang chọn').getByRole('button', { name: 'Đến mốc 05', exact: true }).click()
  await expect(page.getByLabel('Checkpoint mẫu', { exact: true })).toHaveValue('05')
})

