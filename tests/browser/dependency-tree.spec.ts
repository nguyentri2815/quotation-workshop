test('định nghĩa duy nhất ở file thật; resize và đổi chế độ giữ cây, form và tiến độ', async ({ page }) => {
  await page.goto(url)
  const tree = page.getByLabel('Cây phụ thuộc checkpoint 03-summary', { exact: true })
  const frame = page.frameLocator('iframe[title="Preview mẫu checkpoint 03-summary"]')
  await frame.getByLabel('Tên khách hàng', { exact: false }).fill('Giữ form khi đọc cây')
  const origin = await frame.locator('body').evaluate(() => performance.timeOrigin)
  await tree.locator('[data-dependency-node="props"] [data-relation-to="summary"]').click()
  const summary = tree.locator('[data-dependency-node="summary"]')
  await summary.locator('[data-relation-to="format"]').click()
  await expect(tree.locator('[data-dependency-node="format"]')).toHaveCount(1)
  await expect(tree.locator('[data-dependency-node="format"]')).toBeVisible()
  const file = tree.locator('[data-tree-file="quotation/format.ts"]')
  await expect(file.locator('[data-dependency-node="format"]')).toHaveCount(1)
  const scroll = tree.getByTestId('tree-scroll')
  const top = await scroll.evaluate(el => el.scrollTop)
  const handle = page.getByRole('separator', { name: 'Kéo độ rộng preview' })
  const box = (await handle.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + 150); await page.mouse.down(); await page.mouse.move(box.x + 90, box.y + 150, { steps: 5 }); await page.mouse.up()
  expect(await scroll.evaluate(el => el.scrollTop)).toBe(top)
  await expect(tree.locator('[data-dependency-node="format"] [data-dependency-selected="true"]')).toBeVisible()
  await page.getByRole('tab', { name: 'Code', exact: true }).click()
  await expect(page.getByLabel('Source mẫu', { exact: true })).toHaveAttribute('data-file', 'quotation/format.ts')
  await page.getByRole('tab', { name: 'Phụ thuộc của bước', exact: true }).click()
  await expect(tree.locator('[data-dependency-node="format"] [data-dependency-selected="true"]')).toBeVisible()
  expect(await scroll.evaluate(el => el.scrollTop)).toBe(top)
  await expect(frame.getByLabel('Tên khách hàng', { exact: false })).toHaveValue('Giữ form khi đọc cây')
  expect(await frame.locator('body').evaluate(() => performance.timeOrigin)).toBe(origin)
  await expect(page.getByRole('progressbar')).toHaveAttribute('value', '0')
  await page.setViewportSize({ width: 390, height: 900 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: '.verification/dependency-tree-20261030/mobile.png', fullPage: true })
})
