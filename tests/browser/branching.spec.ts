test('Lưu: guard, success, lỗi sau persist, retry occurrence, back và URL', async ({ page }) => {
  await page.goto(base)
  await next(page)
  await expect(page.getByRole('button', { name: 'Tiếp sự kiện →', exact: true })).toBeDisabled()
  await page.locator('[data-branch="guard~pending"]').click()
  await next(page)
  await page.locator('[data-branch="post~handler"]').click()
  await page.locator('[data-branch="handler~persist"]').click()
  await page.locator('[data-branch="persist~response"]').click()
  await page.locator('[data-branch="response~navigate"]').click()
  await next(page)
  await expect(page.getByLabel('Chọn event', { exact: true })).toHaveValue('receipt')
  await page.getByRole('button', { name: 'Quay lại điểm rẽ / Thử nhánh khác', exact: true }).click()
  await page.locator('[data-branch="response~failure"]').click()
  expect(new URLSearchParams(new URL(page.url()).hash.slice(1)).get('path')).not.toContain('navigate')
  await next(page); await next(page)
  await expect(page.getByTestId('flow-inspector')).toContainText('Không có tự retry')
  await next(page); await next(page)
  await expect(page.getByLabel('Chọn event', { exact: true })).toHaveValue('guard')
  const params = new URLSearchParams(new URL(page.url()).hash.slice(1))
  expect(params.get('path')?.split(',').filter(id => id === 'submit')).toHaveLength(2)
  await page.reload()
  await expect(page.getByLabel('Chọn event', { exact: true })).toHaveValue('guard')
  await page.getByRole('button', { name: 'Quay lại', exact: true }).click()
  await expect(page.getByLabel('Chọn event', { exact: true })).toHaveValue('submit')
  await page.goBack()
  await expect(page.getByLabel('Chọn event', { exact: true })).toHaveValue('guard')
  await page.goForward()
  await expect(page.getByLabel('Chọn event', { exact: true })).toHaveValue('submit')
  await expect(page.getByLabel('Checkpoint mẫu', { exact: true })).toHaveValue('09')
  const frame = page.frameLocator('iframe[title="Preview mẫu checkpoint 09"]')
  await expect(frame.getByLabel('Tên khách hàng', { exact: false })).toBeEmpty()
  await expect(page.getByRole('progressbar')).toHaveAttribute('value', '0')
})

