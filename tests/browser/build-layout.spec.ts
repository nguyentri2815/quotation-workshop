import { test, expect } from '@playwright/test'
const codeUrl = '/#journey=2&step=3&sub=4&tab=build'
const treeUrl = '/#journey=2&step=3&sub=3&tab=build&buildView=dependencies&dependencyNode=props'

for (const [width, height] of [[1440,900], [1920,1080], [1152,720], [1536,864]]) {
  test(`vùng đọc ${width}×${height}: chiều cao, ba chế độ, explorer và iframe giữ ngữ cảnh`, async ({ page }) => {
    await page.setViewportSize({ width, height })
    await page.goto(codeUrl)
    const code = page.getByTestId('code-scroll')
    await code.waitFor()
    await expect(page.getByTestId('highlighted-code')).toHaveAttribute('data-ready', 'true')
    const frame = page.frameLocator('iframe[title="Preview mẫu checkpoint 05"]')
    await frame.getByLabel('Tên khách hàng', { exact: false }).fill('Giữ dữ liệu khi đổi bố cục')
    const origin = await frame.locator('body').evaluate(() => performance.timeOrigin)
    const hash = new URL(page.url()).hash
    const mode = page.getByRole('combobox', { name: 'Chế độ làm việc', exact: true })
    const explorer = page.getByRole('button', { name: 'Explorer', exact: true })
    const explorerBody = page.getByLabel('Cấu trúc tính năng checkpoint 05', { exact: true }).locator('[class*="body"]')
    await explorerBody.evaluate(el => { el.scrollTop = 130 })
    const treeScroll = await explorerBody.evaluate(el => el.scrollTop)
    await explorer.click(); await explorer.click()
    expect(await explorerBody.evaluate(el => el.scrollTop)).toBe(treeScroll)
    await code.evaluate(el => { el.scrollTop = 430 })
    const scroll = await code.evaluate(el => el.scrollTop)
    for (const value of ['code', 'preview', 'compare']) {
      await mode.selectOption(value)
      await expect(mode).toHaveValue(value)
      await expect(page.getByRole('button', { name: 'Theo bước mẫu', exact: true })).toHaveCount(value === 'code' ? 0 : 1)
      if (value === 'code') {
        const hiddenControl = page.getByRole('button', { name: 'Theo bước mẫu', exact: true, includeHidden: true })
        await hiddenControl.focus()
        await expect(hiddenControl).not.toBeFocused()
      }
      await expect(page.getByLabel('Thao tác trong bước', { exact: true }).locator('[aria-current="step"]')).toBeInViewport({ ratio: .95 })
      expect((await code.boundingBox())!.height / height).toBeGreaterThanOrEqual(.60)
      expect(await code.evaluate(el => el.scrollTop)).toBe(scroll)
      expect(new URL(page.url()).hash).toBe(hash)
      expect(await frame.locator('body').evaluate(() => performance.timeOrigin)).toBe(origin)
      await expect(frame.getByLabel('Tên khách hàng', { exact: false })).toHaveValue('Giữ dữ liệu khi đổi bố cục')
      expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
      if (value !== 'code') expect((await page.locator('iframe[title="Preview mẫu checkpoint 05"]').boundingBox())!.height / height).toBeGreaterThan(.75)
    }
    expect((await code.boundingBox())!.y + (await code.boundingBox())!.height).toBeGreaterThan(height - 3)
    await expect(page.locator('[class*="stepFooter"]')).toHaveCount(0)
    const separator = page.getByRole('separator', { name: 'Kéo độ rộng preview', exact: true })
    await separator.focus(); await page.keyboard.press('ArrowLeft')
    expect(await frame.locator('body').evaluate(() => performance.timeOrigin)).toBe(origin)
    expect(await code.evaluate(el => el.scrollTop)).toBe(scroll)
    await page.getByRole('button', { name: 'Thông tin preview', exact: true }).click()
    await expect(page.getByRole('dialog', { name: 'Thông tin preview', exact: true })).toContainText('Source: checkpoints/05/')
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'Thông tin preview', exact: true })).toBeFocused()
    const font = await code.locator('[data-line]').first().evaluate(el => getComputedStyle(el).fontSize)
    expect(font).toBe('13px')
    await page.screenshot({ path: `.verification/build-layout-20261031/code-${width}.png` })
  })
}

test('phụ thuộc dùng chung toolbar; chọn Props → PremiumSummary → formatMoney và quay lại', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(treeUrl)
  const tree = page.getByTestId('step-dependencies').getByTestId('tree-scroll')
  expect((await tree.boundingBox())!.height / 900).toBeGreaterThan(.65)
  const workbar = page.locator('[class*="workspaceToolbar"]')
  expect((await workbar.boundingBox())!.height).toBeLessThanOrEqual(44)
  await page.locator('[data-dependency-node="props"] [data-relation-to="summary"]').click()
  await page.locator('[data-dependency-node="summary"] [data-relation-to="format"]').click()
  const selected = page.locator('[data-dependency-node="format"] [data-dependency-selected="true"]')
  await expect(selected).toBeVisible()
  const scroll = await tree.evaluate(el => el.scrollTop)
  for (const mode of ['code','preview','compare']) {
    await page.getByLabel('Chế độ làm việc', { exact: true }).selectOption(mode)
    await expect(selected).toBeVisible()
    expect((await tree.boundingBox())!.height / 900).toBeGreaterThan(.65)
  }
  expect(await tree.evaluate(el => el.scrollTop)).toBe(scroll)
  await page.getByRole('button', { name: 'Quay lại lựa chọn trước', exact: true }).click()
  await expect(page.locator('[data-dependency-node="summary"] [data-dependency-selected="true"]')).toBeVisible()
  await page.goBack()
  await expect(selected).toBeVisible()
  await page.screenshot({ path: '.verification/build-layout-20261031/dependencies-1440.png' })
})

test('mốc nhỏ, bàn phím và Xem source / Quay lại flow không thêm banner', async ({ page }) => {
  await page.goto('/#journey=2&step=1&sub=2&mark=01-field-contract&tab=build')
  await page.getByLabel('Mốc nhỏ trong sub-step', { exact: true }).selectOption('01-field-example')
  await expect(page.getByLabel('Checkpoint mẫu', { exact: true })).toHaveValue('01-field-example')
  await page.getByRole('button', { name: 'Mốc nhỏ tiếp', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Checkpoint mẫu', { exact: true })).toHaveValue('01-field-first')
  await page.goto('/#journey=2&step=5&sub=5&tab=overview&overviewMode=runtime&runtimeFlow=save&runtimeEvent=catch&path=submit,guard,pending,post,failure,catch')
  await page.getByTestId('flow-inspector').getByRole('button', { name: 'Mở đoạn trong Xây từng bước →' }).first().click()
  const button = page.getByRole('button', { name: 'Quay lại flow Lưu bản chào', exact: true })
  await expect(button).toBeVisible()
  expect((await button.boundingBox())!.y).toBeLessThan(65)
  await expect(page.locator('[class*="flowReturn"]')).toHaveCount(0)
  await button.click()
  expect(new URLSearchParams(new URL(page.url()).hash.slice(1)).get('runtimeEvent')).toBe('catch')
})
