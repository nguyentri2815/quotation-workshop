import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
const url = (cp = 's2-03-switch', run = '') => `/?stage=2&version=1${run ? '&run=product-switch&runMode=' + run : ''}#checkpoint=${cp}`
const shell = (page: Page) => page.locator('[data-stage="2"]')
const review = (page: Page, cp = 's2-03-switch') => page.frameLocator(`iframe[title="Preview mẫu checkpoint ${cp}"]`)
const running = (page: Page) => page.frameLocator('iframe[title^="Phiên chạy mẫu s2-"]')
const source = (page: Page) => page.getByLabel('Source mẫu', { exact: true })
async function done(page: Page) { await expect(shell(page)).toHaveAttribute('data-run-status','done',{timeout:60000}) }
async function postCount(page: Page) { return running(page).locator('body').evaluate(() => window.__workshopRun?.network.filter(item => item.kind === 'request' && item.method === 'POST').length ?? -1) }

test('bốn mốc source/preview: baseline → catalog tiêu thụ ngay → selector/state → đổi an toàn', async ({ page }) => {
  for (const [cp, count] of [['s2-00',0],['s2-01-catalog',0],['s2-02-selection',1],['s2-03-switch',1]] as const) {
    await page.goto(url(cp))
    await expect(source(page)).toHaveAttribute('data-checkpoint',cp)
    await expect(source(page).locator('[data-explained="true"]').first()).toBeVisible()
    const frame = review(page,cp)
    await expect(frame.locator('#customerName')).toBeVisible()
    await expect(frame.locator('#productCode')).toHaveCount(count)
    if (cp !== 's2-00') await expect(frame.locator('#product-info')).toContainText('Dữ liệu demo phục vụ học tập')
    if (count) {
      await frame.locator('#customerName').fill('Giữ khi chuyển sản phẩm')
      await frame.locator('#productCode').selectOption('EXTENDED_PROPERTY')
      await expect(frame.locator('#product-info')).toContainText('0,15%')
      await expect(frame.locator('#customerName')).toHaveValue('Giữ khi chuyển sản phẩm')
      await expect(frame.getByRole('button',{name:'Tính phí',exact:true})).toBeDisabled()
    }
    await expect(frame.locator('vite-error-overlay')).toHaveCount(0)
  }
})

test('quan hệ ngay trên cây, file thật/range thật; tab/file/resize không remount preview', async ({ page }) => {
  await page.goto(url())
  const frame = review(page)
  await frame.locator('#customerName').fill('Dữ liệu review nguyên vẹn')
  const origin = await frame.locator('body').evaluate(()=>performance.timeOrigin)
  await page.getByRole('tab',{name:'Phụ thuộc của bước',exact:true}).click()
  const tree=page.getByTestId('step-dependencies')
  await page.getByLabel('Tìm symbol trên cây',{exact:true}).fill('CreateQuotation.changeProduct')
  await page.locator('[data-search-result="change"]').click()
  await tree.locator('[data-definition="pages/CreateQuotation.tsx#CreateQuotation.changeProduct"] [data-relation="change~Cập nhật state~result"]').getByRole('button',{name:'Xem quan hệ',exact:true}).click()
  await tree.getByLabel('Quan hệ đang chọn',{exact:true}).getByRole('button',{name:'Xem code nguồn',exact:true}).click()
  await expect(source(page)).toHaveAttribute('data-file','pages/CreateQuotation.tsx')
  await expect(source(page).locator('[data-explained="true"]').first()).toContainText('setPremium(null)')
  for (const mode of ['code','preview','compare']) {
    await page.getByLabel('Chế độ làm việc',{exact:true}).selectOption(mode)
    expect(await frame.locator('body').evaluate(()=>performance.timeOrigin)).toBe(origin)
  }
  await page.getByRole('tab',{name:'Code',exact:true}).click()
  await page.getByRole('button',{name:'Tùy chọn explorer',exact:true}).click()
  await page.getByRole('button',{name:'Cây thư mục vật lý',exact:true}).click()
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Cây ứng dụng checkpoint s2-03-switch',{exact:true}).locator('[data-file="quotation/products.ts"]').filter({visible:true})).toBeVisible()
  await expect(frame.locator('#customerName')).toHaveValue('Dữ liệu review nguyên vẹn')
})

test('phiên mẫu A → B → A: kết quả DOM, history không POST, thoát giữ review/URL/scroll', async ({ page }) => {
  await page.goto(url())
  const frame = review(page)
  await frame.locator('#customerName').fill('Bản review không bị ghi đè')
  const origin = await frame.locator('body').evaluate(()=>performance.timeOrigin)
  const progress = await page.evaluate(()=>localStorage.getItem('quotation-workshop.behaviors.v2'))
  const hash = new URL(page.url()).hash
  await source(page).getByTestId('code-scroll').evaluate(el=>{el.scrollTop=250})
  const scroll = await source(page).getByTestId('code-scroll').evaluate(el=>el.scrollTop)
  await page.getByRole('button',{name:'Chạy thử',exact:true}).click()
  await page.getByRole('button',{name:'Xem chạy mẫu',exact:true}).click()
  await done(page)
  const runFrame = running(page)
  await expect(runFrame.locator('#productCode')).toHaveValue('BASIC_PROPERTY')
  await expect(runFrame.locator('[aria-labelledby="premium-heading"]')).toContainText('1.100.000')
  expect(await postCount(page)).toBe(0)
  await page.getByRole('button',{name:'Lịch sử quan sát',exact:true}).click()
  const history = page.getByRole('dialog',{name:'Lịch sử quan sát phiên chạy',exact:true})
  await expect(history).toContainText('Phí cũ hết hiệu lực')
  await expect(history).toContainText('Tài sản mở rộng')
  await history.locator('li button').first().click()
  await expect(page.getByLabel('Code liên quan phiên chạy',{exact:true})).toHaveAttribute('data-file','quotation/products.ts')
  expect(await postCount(page)).toBe(0)
  await expect(runFrame.locator('#productCode')).toHaveValue('BASIC_PROPERTY')
  await page.getByRole('button',{name:'Thoát phiên chạy',exact:true}).click()
  await expect(shell(page)).not.toHaveAttribute('data-run-status')
  expect(new URL(page.url()).hash).toBe(hash)
  expect(await frame.locator('body').evaluate(()=>performance.timeOrigin)).toBe(origin)
  await expect(frame.locator('#customerName')).toHaveValue('Bản review không bị ghi đè')
  await expect.poll(()=>source(page).getByTestId('code-scroll').evaluate(el=>el.scrollTop)).toBe(scroll)
  expect(await page.evaluate(()=>localStorage.getItem('quotation-workshop.behaviors.v2'))).toBe(progress)
})

test('mốc 1.2 guided chỉ quan sát lựa chọn, không chạy phí khi chưa nối', async ({ page }) => {
  await page.goto(url('s2-02-selection','guided'))
  const frame = running(page)
  await expect(shell(page)).toHaveAttribute('data-run-status','waiting',{timeout:30000})
  await expect(shell(page)).toHaveAttribute('data-run-step','1')
  await frame.getByRole('button',{name:'Điền dữ liệu mẫu'}).click()
  await expect(shell(page)).toHaveAttribute('data-run-step','2')
  await expect(frame.locator('#productCode')).toHaveValue('BASIC_PROPERTY')
  await frame.locator('#productCode').selectOption('EXTENDED_PROPERTY')
  await expect(shell(page)).toHaveAttribute('data-run-step','3')
  await frame.locator('#productCode').selectOption('BASIC_PROPERTY')
  await done(page)
  await expect(frame.getByRole('button',{name:'Tính phí',exact:true})).toBeDisabled()
  expect(await postCount(page)).toBe(0)
})

for (const [width,height] of [[1440,900],[390,900]]) test(`Chặng 2 ${width}: code/preview đủ rộng, bàn phím và mốc luôn truy cập được`, async ({ page }) => {
  await page.setViewportSize({width,height})
  await page.goto(url('s2-03-switch','demo'))
  await done(page)
  if (width < 700) await page.getByRole('tab',{name:'Hướng dẫn',exact:true}).click()
  await expect(page.getByLabel('Tiến trình sub-step',{exact:true})).not.toBeVisible()
  const bounds = await page.getByLabel('Code liên quan phiên chạy',{exact:true}).getByTestId('code-scroll').boundingBox()
  // Run mode matches Stage 1: checkpoint stays in the header; construction
  // sub-steps return when leaving the run workspace.
  expect(bounds!.height / height).toBeGreaterThan(width < 700 ? .55 : .60)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  await page.getByRole('button',{name:'Thông tin phiên chạy',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'Thông tin phiên chạy',exact:true})).toContainText('Chưa instrument')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button',{name:'Thông tin phiên chạy',exact:true})).toBeFocused()
  await page.screenshot({path:`.verification/stage2-preview/workshop-${width}.png`})
})

test('A lưu/reload được ở mốc cuối; Chặng 1 giữ URL/source/namespace và tiến độ cũ', async ({ page }) => {
  await page.goto(url())
  const frame = review(page)
  await frame.getByRole('button',{name:'Điền dữ liệu mẫu'}).click()
  await frame.getByRole('button',{name:'Tính phí',exact:true}).click()
  await frame.getByRole('button',{name:'Lưu bản chào',exact:true}).click()
  await expect(frame.getByText('Đã lưu bản chào thành công.')).toBeVisible()
  await frame.locator('body').evaluate(()=>location.reload())
  await expect(frame.getByText('Công ty TNHH Mộc An Demo',{exact:true})).toBeVisible()
  const stage2Storage = await page.evaluate(()=>localStorage.getItem('quotation-workshop.stage2.checkpoint.s2-03-switch.v1'))
  expect(stage2Storage).toBeTruthy()
  await page.getByLabel('Chặng học',{exact:true}).selectOption('1')
  await expect(page.getByLabel('Chặng học',{exact:true})).toHaveValue('1')
  await page.goto('/#journey=2&step=3&sub=4&tab=build')
  await expect(page.getByLabel('Checkpoint mẫu',{exact:true})).toHaveValue('05')
  const old = page.frameLocator('iframe[title="Preview mẫu checkpoint 05"]')
  await expect(old.locator('#productCode')).toHaveCount(0)
  await old.getByRole('button',{name:'Điền dữ liệu mẫu'}).click()
  await old.getByRole('button',{name:'Tính phí',exact:true}).click()
  await expect(old.locator('[aria-labelledby="premium-heading"]')).toContainText('1.100.000')
  expect(await page.evaluate(()=>localStorage.getItem('quotation-workshop.stage2.checkpoint.s2-03-switch.v1'))).toBe(stage2Storage)
})
