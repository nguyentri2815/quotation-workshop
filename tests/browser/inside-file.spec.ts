test('panel rộng nằm cạnh code và mở quan hệ có đường quay lại', async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('/#step=11&tab=build&file=pages/CreateQuotation.tsx&section=save')
  const panel = page.getByLabel('Source mẫu', { exact: true })
  await panel.getByRole('button', { name: 'Bên trong file', exact: true }).click()
  const inside = panel.getByRole('complementary', { name: 'Bên trong file' })
  const code = panel.getByTestId('code-scroll')
  expect((await code.boundingBox())!.width).toBeGreaterThan(500)
  const asideBox = (await inside.boundingBox())!, codeBox = (await code.boundingBox())!
  expect(asideBox.x).toBeGreaterThanOrEqual(codeBox.x + codeBox.width - 1)
  await inside.locator('[data-section="save"]').scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'test-results/inside-file-wide.png', fullPage: true })
  await inside.getByRole('button', { name: '↗ POST qua client', exact: true }).click()
  await expect(panel).toHaveAttribute('data-file', 'api/quotations.ts')
  await expect(inside.locator('[data-section="create"]')).toHaveAttribute('data-active', 'true')
  await inside.getByRole('button', { name: 'Quay lại lựa chọn trước', exact: true }).click()
  await expect(panel).toHaveAttribute('data-file', 'pages/CreateQuotation.tsx')
  await expect(inside.locator('[data-section="save"]')).toHaveAttribute('data-active', 'true')
})
