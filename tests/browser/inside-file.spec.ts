import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('phân tích state / handler / JSX: toàn file, range riêng, nhiều vị trí và history', async ({ page }) => {
  await page.goto('/#step=11&sub=0&tab=build&file=pages/CreateQuotation.tsx&symbol=save')
  const panel = page.getByLabel('Source mẫu', { exact: true })
  const frame = page.frameLocator('iframe[title="Preview mẫu checkpoint 11"]')
  await expect(frame.getByLabel('Tên khách hàng', { exact: false })).toBeVisible()
  const origin = await frame.locator('body').evaluate(() => performance.timeOrigin)
  const raw = await readFile('checkpoints/11/pages/CreateQuotation.tsx', 'utf8')
  const count = raw.trimEnd().split(/\r?\n/).length
  await expect(panel.locator('[data-line]')).toHaveCount(count)
  const code = panel.getByTestId('code-scroll')
  await expect.poll(() => code.evaluate(el => el.scrollTop)).toBeGreaterThan(100)
  const guide = page.locator('[class*="buildSession"]')
  const scrollBefore = await guide.evaluate(el => el.scrollTop)
  const ranges: number[] = []
  for (const id of ['draft', 'premium', 'calculate', 'save', 'customer', 'asset', 'actions', 'dialog']) {
    await panel.getByRole('button', { name: 'Bên trong file', exact: true }).click()
    const analysis = panel.getByRole('complementary', { name: 'Bên trong file' })
    await analysis.locator(`[data-section="${id}"]`).getByRole('button', { name: 'Xem trong code', exact: true }).click()
    await expect(panel.locator('[data-line]')).toHaveCount(count)
    const highlights = panel.locator('[data-explained="true"]')
    expect(await highlights.count()).toBeGreaterThan(0)
    expect(await highlights.count()).toBeLessThan(90)
    ranges.push(Number(await highlights.first().getAttribute('data-line')))
    const box = await code.boundingBox()
    const target = await highlights.first().boundingBox()
    expect(target!.y).toBeGreaterThanOrEqual(box!.y)
    expect(target!.y).toBeLessThan(box!.y + box!.height)
    expect(await guide.evaluate(el => el.scrollTop)).toBe(scrollBefore)
    expect(await page.evaluate(() => window.scrollY)).toBe(0)
  }
  expect(new Set(ranges).size).toBe(ranges.length)
  await panel.getByRole('button', { name: 'Bên trong file', exact: true }).click()
  await panel.locator('[data-section="errors"]').getByRole('button', { name: 'Xem trong code', exact: true }).click()
  const first = await panel.locator('[data-explained="true"]').first().getAttribute('data-line')
  await panel.getByRole('button', { name: /Tiếp vị trí/ }).click()
  const second = await panel.locator('[data-explained="true"]').first().getAttribute('data-line')
  expect(first).not.toBe(second)
  await page.goBack()
  await expect(panel.locator('[data-explained="true"]').first()).toHaveAttribute('data-line', first!)
  await page.goForward()
  await expect(panel.locator('[data-explained="true"]').first()).toHaveAttribute('data-line', second!)
  await code.evaluate(el => { el.scrollTop = 0 })
  await panel.getByRole('button', { name: 'Bên trong file', exact: true }).click()
  expect(await code.evaluate(el => el.scrollTop)).toBe(0)
  await expect(panel.locator('[data-section="errors"]')).toHaveAttribute('data-active', 'true')
  await panel.getByRole('button', { name: 'Đóng phân tích' }).click()
  await panel.getByRole('button', { name: 'Đến đoạn liên quan', exact: true }).click()
  expect(await code.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  expect(await frame.locator('body').evaluate(() => performance.timeOrigin)).toBe(origin)
  await page.screenshot({ path: 'test-results/inside-file-desktop.png', fullPage: true })
})

test('cây tự mở nhánh, cuộn file theo URL, nhiều file liên quan và không giành cuộn', async ({ page }) => {
  await page.goto('/#step=11&tab=build&file=main.tsx&symbol=start')
  await page.getByRole('button', { name: 'Tùy chọn explorer', exact: true }).click()
  await page.getByRole('button', { name: 'Cây thư mục vật lý', exact: true }).click()
  await page.getByRole('button', { name: 'Đóng tùy chọn explorer', exact: true }).click()
  const tree = page.getByLabel('Cây ứng dụng checkpoint 11')
  const scroll = tree.getByTestId('tree-scroll')
  await tree.getByRole('button', { name: 'quotation', exact: true }).click()
  await scroll.evaluate(el => { el.scrollTop = 0 })
  await page.evaluate(() => {
    const query = new URLSearchParams(location.hash.slice(1))
    query.set('file', 'quotation/types.ts'); query.set('symbol', 'sampleDraft')
    location.hash = query.toString()
  })
  await expect(tree.getByRole('button', { name: 'quotation', exact: true })).toHaveAttribute('aria-expanded', 'true')
  const selected = tree.locator('[data-file="quotation/types.ts"]')
  await expect(selected).toHaveAttribute('data-selected', 'true')
  await expect(selected).toContainText('Đang xem')
  const box = await scroll.boundingBox(), target = await selected.boundingBox()
  expect(target!.y).toBeGreaterThanOrEqual(box!.y)
  expect(target!.y + target!.height).toBeLessThanOrEqual(box!.y + box!.height + 1)
  const palette = await selected.evaluate(el => ({ bg: getComputedStyle(el).backgroundColor, left: getComputedStyle(el).borderLeftWidth }))
  const related = tree.locator('[data-related="true"][data-selected="false"]').first()
  expect(await related.count()).toBe(1)
  expect(await related.evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(palette.bg)
  expect(palette.left).toBe('5px')
  await scroll.evaluate(el => { el.scrollTop = 0 })
  await page.getByRole('button', { name: 'Bên trong file', exact: true }).click()
  expect(await scroll.evaluate(el => el.scrollTop)).toBe(0)
  const panel = page.getByLabel('Source mẫu', { exact: true })
  await panel.locator('[data-section="quotation"]').getByRole('button', { name: 'Xem trong code', exact: true }).click()
  await expect(panel.locator('[data-explained="true"]').first().getByTestId('source-line')).toContainText('export interface Quotation')
  await page.screenshot({ path: 'test-results/tree-selection.png', fullPage: true })
})

