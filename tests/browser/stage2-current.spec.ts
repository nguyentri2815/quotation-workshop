import {expect,test} from '@playwright/test'
import type {Page} from '@playwright/test'
const ids=['s2-r3-00','s2-r3-catalog','s2-r3-entry','s2-r3-panel','s2-r3-validation','s2-r3-pricing','s2-r3-complete']
const url=(id=ids[6],extra='')=>`/?stage=2&version=3#checkpoint=${id}${extra}`
const preview=(p:Page,id:string)=>p.frameLocator(`iframe[title="Preview mẫu checkpoint ${id}"]`)
test('hành trình mới chỉ có bảy mốc v3; source/preview không đi qua selector cũ',async({page})=>{
 test.setTimeout(120000)
 for(const [order,id]of ids.entries()){
  await page.goto(url(id))
  await expect(page.locator('[data-workspace="shared"][data-stage="2"]')).toBeVisible()
  const picker=page.getByLabel('Checkpoint mẫu',{exact:true})
  await expect(picker).toHaveCount(1)
  expect(await picker.locator('option').evaluateAll(options=>options.map(o=>(o as HTMLOptionElement).value))).toEqual(ids)
  const app=preview(page,id)
  if(order===0)await expect(app.locator('#customerName')).toBeVisible()
  else{
   await expect(app.getByRole('heading',{name:'Chọn sản phẩm',exact:true})).toBeVisible()
   if(order===1)await expect(app.getByRole('button',{name:'Tạo bản chào Tài sản cơ bản',exact:true})).toBeDisabled()
   else{
    await app.getByRole('link',{name:'Tạo bản chào Tài sản mở rộng',exact:true}).click()
    await expect(app.locator('#product-info')).toHaveAttribute('data-product','EXTENDED_PROPERTY')
    await expect(app.locator('#root select')).toHaveCount(0)
    await expect(app.locator('form article')).toHaveCount(0)
    await expect(app.locator('[data-product-name]')).toHaveText('Tài sản mở rộng')
    if(order===2)await expect(app.getByRole('button',{name:'Đổi sản phẩm',exact:true})).toHaveCount(0)
    else await expect(app.getByRole('button',{name:'Đổi sản phẩm',exact:true})).toBeVisible()
    if(order<6)await expect(app.getByRole('button',{name:'Lưu bản chào',exact:true})).toBeDisabled()
   }
  }
  await expect(app.locator('#productCode')).toHaveCount(0)
  await expect(app.locator('#root')).not.toContainText('Preview 2')
 }
})
