test('viewport: chỉ pan khi cần, khám phá tạm ngừng follow, đổi flow/resize/fullscreen giữ ngữ cảnh', async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto(save)
  const viewport = page.locator('[data-testid="runtime-flow"] .react-flow__viewport')
  await expect(flowEvent(page)).toHaveAttribute('data-event', 'submit')
  await page.getByRole('button', { name: 'Đến sự kiện', exact: true }).click()
  const zoom = async () => Number((await viewport.getAttribute('style'))!.match(/scale\(([^)]+)\)/)![1])
  const startZoom = await zoom()
  const startTransform = await viewport.getAttribute('style')
  await next(page)
  await expect(viewport).toHaveAttribute('style', startTransform!)
  const canvas = page.getByLabel('Sơ đồ có nhánh Lưu bản chào', { exact: true })
  const box = (await canvas.boundingBox())!
  await page.mouse.move(box.x + 35, box.y + 140); await page.mouse.down(); await page.mouse.move(box.x + 120, box.y + 200, { steps: 5 }); await page.mouse.up()
  await expect(page.getByRole('button', { name: 'Theo tiếp sự kiện', exact: true })).toHaveAttribute('aria-pressed', 'false')
  const manual = await viewport.getAttribute('style')
  await page.locator('[data-branch="guard~pending"]').click()
  await expect(viewport).toHaveAttribute('style', manual!)
  await page.getByRole('button', { name: 'Theo tiếp sự kiện', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Theo sự kiện', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(await zoom()).toBe(startZoom)
  const params = new URLSearchParams(new URL(page.url()).hash.slice(1))
  const followed = await viewport.getAttribute('style')
  await page.getByRole('button', { name: 'Toàn màn hình', exact: true }).click()
  const fullscreen = page.getByRole('dialog', { name: 'Toàn màn hình flow và inspector', exact: true })
  expect((await fullscreen.boundingBox())!.width).toBeGreaterThan(1800)
  await expect(viewport).toHaveAttribute('style', followed!)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Toàn màn hình', exact: true })).toBeFocused()
  await expect(viewport).toHaveAttribute('style', followed!)
  await setWidthPreset(page, 'preview')
  await expect(viewport).toHaveAttribute('style', followed!)
  await togglePreview(page, 'Thu preview')
  await expect(viewport).toHaveAttribute('style', followed!)
  await selectBehavior(page, 'calculate')
  await selectBehavior(page, 'save')
  await expect(viewport).toHaveAttribute('style', followed!)
  await selectFlowEvent(page, 'pending')
  // Same event was restored manually; viewport remained on this flow's saved location.
  expect(await zoom()).toBe(startZoom)
  expect(params.get('path')).toBe('submit,guard,pending')
})

